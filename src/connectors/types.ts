import type {
  Customer,
  Invoice,
  InvoiceLineItem,
  PortalAccount,
  Property,
  Vendor,
} from "@prisma/client";

/**
 * How VendorSync can talk to an outside portal.
 *  API     – the portal publishes a vendor-usable API; fully automated.
 *  EMAIL   – the portal (or customer AP team) accepts invoices by email; automated send, manual confirm.
 *  BROWSER – no API. Playwright-driven automation of the vendor's own login (opt-in, see browser.ts).
 *  MANUAL  – VendorSync tracks status and gives a checklist + deep link; a human does the clicks.
 */
export type IntegrationMode = "API" | "EMAIL" | "BROWSER" | "MANUAL";

export type PortalFunction = "COMPLIANCE" | "INVOICES" | "PAYMENTS";

export type ConnectorResult = {
  ok: boolean;
  message: string;
  details?: Record<string, unknown>;
};

export type SubmissionResult = ConnectorResult & {
  /** Confirmation / reference from the remote system, if any. */
  externalRef?: string;
  /** Status to record on the InvoiceSubmission row. */
  status: "PENDING" | "SENT" | "ACCEPTED" | "FAILED";
};

export type InvoicePayload = {
  vendor: Vendor;
  customer: Customer;
  property: Property | null;
  invoice: Invoice;
  lineItems: InvoiceLineItem[];
  /** Rendered invoice PDF (generated by src/lib/invoice-pdf.ts or the user's upload). */
  pdf: Buffer;
  pdfFileName: string;
};

export type ConnectorContext = {
  vendor: Vendor;
  account: PortalAccount;
  /** Decrypts the stored secret on demand so it never sits in memory longer than needed. */
  getSecret: () => string | null;
  log: (line: string) => void;
};

export interface PortalConnector {
  key: string;
  name: string;
  owner: string;
  website: string;
  defaultLoginUrl: string;
  mode: IntegrationMode;
  handles: PortalFunction[];
  /** One-paragraph description shown in the UI. */
  summary: string;
  /** Plain-language explanation of exactly how VendorSync integrates, and its limits. */
  integrationNotes: string;
  /** Checklist shown when a human needs to finish the job in the portal. */
  manualSteps: {
    submitInvoice?: string[];
    updateCompliance?: string[];
  };

  testConnection?(ctx: ConnectorContext): Promise<ConnectorResult>;
  submitInvoice?(ctx: ConnectorContext, payload: InvoicePayload): Promise<SubmissionResult>;
  syncCompliance?(ctx: ConnectorContext): Promise<ConnectorResult>;
  pullPayments?(ctx: ConnectorContext): Promise<ConnectorResult>;
}
